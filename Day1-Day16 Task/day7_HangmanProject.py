game_over = False
life = 0

while not game_over:
    input_char = str(input("Guess a letter: ").lower())
    k = 0
    flag = False
    for j in word:
        if input_char == j:
            guessed_letters[k] = j
            flag = True
        k+=1
    display = "".join(guessed_letters)
    print(display)
    if flag :
        print(HANGMANPICS[life])
    else:
        life+=1
        print(HANGMANPICS[life])

    if life >5 :
        print("You lose")
        game_over = True
    elif "_" not in display:
        print("You Win!")
